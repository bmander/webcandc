/*
** webcandc: portable C++ port of FILLQUAD.ASM (Westwood 32-bit library,
** reference/CnC_Red_Alert/WIN32LIB/DRAWBUFF/FILLQUAD.ASM).
**
**   Buffer_Fill_Quad -- GraphicViewPortClass::Fill_Quad
**
** The port keeps the original's clipping, rasterization rules and quirks
** (the clip rectangle is [XPos, Width] x [YPos-1, Height-1]; the topmost span
** and the right end of each span are not drawn).
*/

#include "GBUFFER.H"

namespace {

enum { SLOT_VACANT = 0x8000 };		// each 16-bit half of a vacant span

/*
** The span buffer supplied by the caller holds one 32-bit entry per scanline:
** a 16-bit "left" slot followed by a 16-bit "right" slot.
*/
struct QuadState {
	int clip_min_x;
	int clip_max_x;
	int clip_min_y;
	int clip_max_y;
	int left_clip_base[2];		// y extents of edges generated by clipping
	int left_clip_count;
	int right_clip_base[2];
	int right_clip_count;
	int scanline_min;
	unsigned short *span;
};

inline bool Span_Vacant(unsigned short const *s)
{
	return s[0] == SLOT_VACANT && s[1] == SLOT_VACANT;
}

/*
** Fill the left slot if the span is vacant; the right slot is always written.
*/
inline void Put_Slot(unsigned short *s, int x)
{
	if (Span_Vacant(s)) s[0] = (unsigned short)x;
	s[1] = (unsigned short)x;
}

/*
** Scan convert an edge from (xa,ya) to (xb,yb) into the span buffer.
*/
void Scan_Convert(QuadState &q, int xa, int ya, int xb, int yb)
{
	if (ya == yb) return;
	if (ya > yb) {
		int t = xa; xa = xb; xb = t;
		t = ya; ya = yb; yb = t;
	}

	int const dy = yb - ya;
	int const idx = ya - q.scanline_min;
	unsigned short *s = q.span + 2 * idx;
	int const dx = xb - xa;
	int x = xa;

	/*
	** The span at the edge's upper vertex is only written when it is the
	** topmost span of the quad.
	*/
	if (dx == 0) {
		if (idx <= 0) Put_Slot(s, x);
		for (int n = dy; n > 0; n--) {
			s += 2;
			Put_Slot(s, x);
		}
		return;
	}

	int const realignment = 2 * dy;
	int const quotient = dx / dy;			// idiv truncates toward zero
	int step = 2 * (dx % dy);
	int adjust = 1;
	if (step < 0) {
		step = -step;
		adjust = -1;
	}
	int error = -dy;

	if (idx <= 0) Put_Slot(s, x);
	for (int n = dy; n > 0; n--) {
		s += 2;
		x += quotient;
		error += step;
		if (error > 0) {
			x += adjust;
			error -= realignment;
		}
		Put_Slot(s, x);
	}
}

/*
** Clip point (px,py) against the horizontal line y = clip_y, using (ox,oy)
** as the other end of the edge.
*/
inline void Clip_Vert(int clip_y, int &px, int &py, int ox, int oy)
{
	px = px + (int)(((long long)(clip_y - py) * (ox - px)) / (oy - py));
	py = clip_y;
}

/*
** Clip point (px,py) against the vertical line x = clip_x.
*/
inline void Clip_Horiz(int clip_x, int &px, int &py, int ox, int oy)
{
	py = py + (int)(((long long)(clip_x - px) * (oy - py)) / (ox - px));
	px = clip_x;
}

inline int Clamp_Y(QuadState const &q, int y)
{
	if (y < q.clip_min_y) y = q.clip_min_y;
	if (y > q.clip_max_y) y = q.clip_max_y;
	return y;
}

inline void Record_Clip(int *base, int &count, int y)
{
	if (count == 0) {
		base[0] = y;
		base[1] = y;		// (the original left this uninitialized)
		count = 1;
	} else {
		base[1] = y;
	}
}

/*
** Clipping subroutine table: 1 = left, 2 = right, 4 = above, 8 = below.
*/
void Clip_Point(QuadState &q, int code, int &px, int &py, int ox, int oy)
{
	switch (code) {
		case 1:
			Clip_Horiz(q.clip_min_x, px, py, ox, oy);
			Record_Clip(q.left_clip_base, q.left_clip_count, Clamp_Y(q, py));
			break;

		case 2:
			Clip_Horiz(q.clip_max_x, px, py, ox, oy);
			Record_Clip(q.right_clip_base, q.right_clip_count, Clamp_Y(q, py));
			break;

		case 4:
			Clip_Vert(q.clip_min_y, px, py, ox, oy);
			break;

		case 8:
			Clip_Vert(q.clip_max_y, px, py, ox, oy);
			break;

		default:
			break;
	}
}

inline int Left_Right_Bits(QuadState const &q, int x)
{
	int bits = 0;
	if (x < q.clip_min_x) bits |= 1;
	if (x > q.clip_max_x) bits |= 2;
	return bits;
}

inline int Up_Down_Bits(QuadState const &q, int y)
{
	int bits = 0;
	if (y < q.clip_min_y) bits |= 4;
	if (y > q.clip_max_y) bits |= 8;
	return bits;
}

/*
** Clip an edge against the viewport, then scan convert it. The register
** shuffling of the original (which end gets clipped first) is preserved so
** integer rounding matches exactly.
*/
void Clip_And_Scan_Convert(QuadState &q, int xa, int ya, int xb, int yb)
{
	int ax = xa, ay = ya;		// eax, ebx
	int cx = xb, cy = yb;		// ecx, edx
	int t;

	int s = Left_Right_Bits(q, ax);
	t = ax; ax = cx; cx = t;
	t = ay; ay = cy; cy = t;
	int e = s;
	s = Left_Right_Bits(q, ax);
	if (e | s) {
		if (e & s) return;
		Clip_Point(q, s, ax, ay, cx, cy);
		t = ax; ax = cx; cx = t;
		t = ay; ay = cy; cy = t;
		Clip_Point(q, e, ax, ay, cx, cy);
	}

	s = Up_Down_Bits(q, ay);
	t = ax; ax = cx; cx = t;
	t = ay; ay = cy; cy = t;
	e = s;
	s = Up_Down_Bits(q, ay);
	if (e | s) {
		if (e & s) return;
		Clip_Point(q, s, ax, ay, cx, cy);
		t = ax; ax = cx; cx = t;
		t = ay; ay = cy; cy = t;
		Clip_Point(q, e, ax, ay, cx, cy);
	}

	Scan_Convert(q, ax, ay, cx, cy);
}

}	// namespace


/***************************************************************************
 * Buffer_Fill_Quad -- Fills a (convex) quadrilateral with a solid color.  *
 *                                                                         *
 * INPUT:   thisptr   - GraphicViewPortClass to draw on                    *
 *          span_buff - scratch buffer, 4 bytes per scanline of the quad   *
 *          x0..y3    - the four vertices, in order around the quad        *
 *          color     - fill color                                         *
 *=========================================================================*/
extern "C" VOID __cdecl Buffer_Fill_Quad(void * thisptr, VOID *span_buff, int x0, int y0, int x1, int y1,
						 	int x2, int y2, int x3, int y3, int color)
{
	GraphicViewPortClass *vp = (GraphicViewPortClass *)thisptr;
	QuadState q;

	q.clip_min_x = vp->Get_XPos();
	q.clip_min_y = vp->Get_YPos() - 1;
	q.clip_max_x = vp->Get_Width();
	q.clip_max_y = vp->Get_Height() - 1;
	long const bpr = vp->Get_Width() + vp->Get_XAdd() + vp->Get_Pitch();

	/*
	** Vertical extent of the quad before clipping, clamped to the viewport.
	*/
	int smin = y0;
	if (y1 < smin) smin = y1;
	if (y2 < smin) smin = y2;
	if (y3 < smin) smin = y3;
	int smax = y0;
	if (y1 > smax) smax = y1;
	if (y2 > smax) smax = y2;
	if (y3 > smax) smax = y3;
	smin = Clamp_Y(q, smin);
	smax = Clamp_Y(q, smax);

	int const count = smax - smin;
	if (count == 0 || span_buff == NULL) return;

	q.span = (unsigned short *)span_buff;
	for (int i = 0; i <= count; i++) {
		q.span[2 * i] = SLOT_VACANT;
		q.span[2 * i + 1] = SLOT_VACANT;
	}
	q.scanline_min = smin;
	q.left_clip_count = 0;
	q.right_clip_count = 0;

	Clip_And_Scan_Convert(q, x0, y0, x1, y1);
	Clip_And_Scan_Convert(q, x1, y1, x2, y2);
	Clip_And_Scan_Convert(q, x2, y2, x3, y3);
	Clip_And_Scan_Convert(q, x3, y3, x0, y0);

	/*
	** Scan convert the vertical edges generated by clipping.
	*/
	if (q.left_clip_count) {
		Scan_Convert(q, q.clip_min_x, q.left_clip_base[0], q.clip_min_x, q.left_clip_base[1]);
	}
	if (q.right_clip_count) {
		Scan_Convert(q, q.clip_max_x, q.right_clip_base[0], q.clip_max_x, q.right_clip_base[1]);
	}

	/*
	** Fill the spans. Rasterization rule: the topmost span is not drawn, and
	** each span covers [min(left,right), max(left,right)).
	*/
	unsigned char *const base = (unsigned char *)vp->Get_Offset();
	for (int i = 1; i <= count; i++) {
		unsigned short const *s = q.span + 2 * i;
		if (Span_Vacant(s)) continue;
		int const l = s[0];
		int const r = s[1];
		int const start = (l < r) ? l : r;
		int const len = (l < r) ? (r - l) : (l - r);
		if (len) memset(base + (long)(smin + i) * bpr + start, (unsigned char)color, len);
	}
}
